#!/usr/bin/env python3
"""Measure EfficientViT-SAM-L0 generic RGB-D segmentation on a demo image.

The depth plane is synthetic, generated by the same mock-depth function used
by the existing RGB-D demo publisher.  It exercises the RGB-D/3-D tracker
path; it does not claim physical depth accuracy.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from seg_web_node.efficientvit_backend import EfficientViTSamL0Backend
from seg_web_node.geometry import CameraIntrinsics, deproject, robust_mask_center
from seg_web_node.mock_depth import make_mock_depth
from seg_web_node.tasc_belief import StableObjectIdTracker
from seg_web_node.visualization import render_segmented_rgbd


def percentile(values: list[float], value: float) -> float:
    return float(np.percentile(np.asarray(values, dtype=np.float64), value))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", type=Path, default=Path("output/sam3_demo.jpg"))
    parser.add_argument("--weight", type=Path, default=Path("/models/efficientvit_sam/efficientvit_sam_l0.pt"))
    parser.add_argument("--reinitialization", choices=("all", "central"), default="central")
    parser.add_argument("--reinitialize-interval", type=int, default=15)
    parser.add_argument("--warmup", type=int, default=10)
    parser.add_argument("--iterations", type=int, default=60)
    parser.add_argument("--points-per-side", type=int, default=8)
    parser.add_argument("--output", type=Path, default=Path("output/efficientvit_l0_rgbd_benchmark.jpg"))
    parser.add_argument("--json-output", type=Path, default=Path("output/efficientvit_l0_rgbd_benchmark.json"))
    args = parser.parse_args()
    if not args.weight.is_file():
        raise SystemExit(f"missing checkpoint: {args.weight}; run tools/cache_efficientvit_l0.py in the container first")
    image = cv2.imread(str(args.image), cv2.IMREAD_COLOR)
    if image is None:
        raise SystemExit(f"cannot read image: {args.image}")
    image = cv2.resize(image, (640, 360), interpolation=cv2.INTER_AREA)
    depth = make_mock_depth(image)
    backend = EfficientViTSamL0Backend(
        threshold=0.50,
        min_area_px=400,
        weight_path=args.weight,
        reinitialization=args.reinitialization,
        reinitialize_interval_frames=args.reinitialize_interval,
        automatic_points_per_side=args.points_per_side,
        max_masks=12,
    )
    import torch

    for _ in range(args.warmup):
        backend.infer(image, ["object"], depth_raw=depth, depth_scale_um=1000)
    torch.cuda.synchronize()
    tracker = StableObjectIdTracker(max_distance_m=0.25, missing_ttl_frames=5)
    intrinsics = CameraIntrinsics(640, 360, 600.0, 600.0, 320.0, 180.0)
    xyz = deproject(depth, intrinsics, 1000, 0.15, 3.0)
    elapsed_ms: list[float] = []
    last = None
    last_tracks: list[dict[str, object]] = []
    for _ in range(args.iterations):
        torch.cuda.synchronize()
        started = time.perf_counter()
        masks, boxes, scores, labels = backend.infer(
            image, ["object"], depth_raw=depth, depth_scale_um=1000
        )
        torch.cuda.synchronize()
        elapsed_ms.append((time.perf_counter() - started) * 1000.0)
        detections: list[dict[str, object]] = []
        frame_tracks: list[dict[str, object]] = []
        for index, mask in enumerate(masks):
            center = robust_mask_center(xyz, mask, min_valid_points=20)
            if center is None:
                continue
            point, pixel, count = center
            detections.append({"index": index, "label": labels[index], "center_goal_m": point})
            frame_tracks.append({"index": index, "center_camera_m": point.tolist(), "pixel_uv": list(pixel), "depth_points": count})
        assignments = tracker.assign(detections)
        for entry in frame_tracks:
            entry["track_id"] = assignments.get(int(entry["index"]))
        last_tracks = frame_tracks
        last = (masks, boxes, scores, labels)
    if last is None:
        raise RuntimeError("no benchmark frames ran")
    masks, boxes, scores, labels = last
    overlay, _ = render_segmented_rgbd(image, depth, masks, boxes, scores, labels, 1000)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(args.output), overlay)
    report = {
        "model": "efficientvit-sam-l0",
        "reinitialization": args.reinitialization,
        "reinitialize_interval_frames": args.reinitialize_interval,
        "image": str(args.image),
        "depth": "synthetic mock depth from seg_web_node.mock_depth",
        "iterations": args.iterations,
        "latency_ms": {"mean": round(float(np.mean(elapsed_ms)), 3), "p50": round(percentile(elapsed_ms, 50), 3), "p95": round(percentile(elapsed_ms, 95), 3), "p99": round(percentile(elapsed_ms, 99), 3)},
        "period_hz_mean": round(1000.0 / float(np.mean(elapsed_ms)), 3),
        "masks_last_frame": int(len(masks)),
        "tracks_last_frame": last_tracks,
        "overlay": str(args.output),
        "backend": backend.metadata,
    }
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
